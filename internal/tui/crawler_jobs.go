// CrawlerParams is one background job's crawler configuration. It maps 1:1
// onto the crawler CLI flags (cmd/crawler.go) so the job can be re-launched as
// a detached process.
type CrawlerParams struct {
	Mode             CrawlMode `json:"mode"`
	StartPage        int       `json:"start_page"`
	Pages            int       `json:"pages"`
	MonitorPages     int       `json:"monitor_pages"`
	Loop             bool      `json:"loop"`
	LoopDelaySeconds int       `json:"loop_delay_seconds"`
	PageDelaySeconds int       `json:"page_delay_seconds"`
	PostBatchSize    int       `json:"post_batch_size"`
	CommentLimit     int       `json:"comment_limit"`
	FetchImages      bool      `json:"fetch_images"`
	SaveRawJSON      bool      `json:"save_raw_json"`
	ConvertWebp      bool      `json:"convert_webp"`
	ThumbnailStartID int       `json:"thumbnail_start_id"`
	ThumbnailEndID   int       `json:"thumbnail_end_id"`
}

func defaultCrawlerParams() CrawlerParams {
	return CrawlerParams{
		Mode:             CrawlSequential,
		StartPage:        1,
		Pages:            0,
		MonitorPages:     3,
		LoopDelaySeconds: 60,
		PageDelaySeconds: 1,
		PostBatchSize:    200,
		CommentLimit:     200,
		ConvertWebp:      true,
		ThumbnailStartID: 30000,
		ThumbnailEndID:   31000,
	}
}

// CrawlerJob is one background crawler process managed by the sync page.
type CrawlerJob struct {
	ID        string        `json:"id"`
	Name      string        `json:"name"`
	Params    CrawlerParams `json:"params"`
	PID       int           `json:"pid"`
	StartedAt time.Time     `json:"started_at"`

	// Stopping and Progress are runtime-only state.
	Stopping bool   `json:"-"`
	Progress string `json:"-"`
}

type CrawlerJobState int

const (
	JobNeverStarted CrawlerJobState = iota
	JobRunning
	JobStopping
	JobFinished
)

func (j CrawlerJob) State() CrawlerJobState {
	if !jobAlive(j.PID) {
		if j.PID == 0 {
			return JobNeverStarted
		}
		return JobFinished
	}
	if j.Stopping {
		return JobStopping
	}
	return JobRunning
}

func (j CrawlerJob) Uptime() time.Duration {
	if j.StartedAt.IsZero() || !jobAlive(j.PID) {
		return 0
	}
	return time.Since(j.StartedAt)
}

type crawlerJobRegistry struct {
	Version int          `json:"version"`
	Jobs    []CrawlerJob `json:"jobs"`
}

const crawlerJobRegistryVersion = 1

func newCrawlerJob(name string, params CrawlerParams) CrawlerJob {
	return CrawlerJob{
		ID:     fmt.Sprintf("job-%d", time.Now().UnixNano()),
		Name:   name,
		Params: params,
	}
}

func loadCrawlerJobs() ([]CrawlerJob, error) {
	path, err := config.CrawlerJobsPath()
	if err != nil {
		return nil, err
	}
	data, err := os.ReadFile(path)
	if os.IsNotExist(err) {
		return nil, nil
	}
	if err != nil {
		return nil, err
	}
	var registry crawlerJobRegistry
	if err := json.Unmarshal(data, &registry); err != nil {
		return nil, fmt.Errorf("解析后台任务失败: %w", err)
	}
	for i := range registry.Jobs {
		registry.Jobs[i].Progress = jobProgressLine(registry.Jobs[i])
	}
	return registry.Jobs, nil
}

// saveCrawlerJobs writes the registry atomically so a crash cannot truncate it.
func saveCrawlerJobs(jobs []CrawlerJob) error {
	path, err := config.CrawlerJobsPath()
	if err != nil {
		return err
	}
	if err := os.MkdirAll(filepath.Dir(path), 0755); err != nil {
		return err
	}
	data, err := json.MarshalIndent(crawlerJobRegistry{Version: crawlerJobRegistryVersion, Jobs: jobs}, "", "  ")
	if err != nil {
		return err
	}
	tmp := path + ".tmp"
	if err := os.WriteFile(tmp, append(data, '\n'), 0644); err != nil {
		return err
	}
	return os.Rename(tmp, path)
}

// jobLogPath is the per-job log file. The ID is generated by newCrawlerJob, so
// the file name never contains user input.
func jobLogPath(job CrawlerJob) (string, error) {
	dir, err := config.CrawlerJobLogDir()
	if err != nil {
		return "", err
	}
	id := job.ID
	if id == "" || strings.ContainsAny(id, `/\`) {
		return "", fmt.Errorf("非法任务 ID: %q", id)
	}
	return filepath.Join(dir, id+".log"), nil
}

// jobLogPathByID is the log path for code that only knows the job ID.
func jobLogPathByID(id string) string {
	path, err := jobLogPath(CrawlerJob{ID: id})
	if err != nil {
		return ""
	}
	return path
}

func jobArgs(job CrawlerJob) []string {
	p := job.Params
	switch p.Mode {
	case CrawlFetchImages:
		return []string{"crawler", "fetch-images", "--convert-webp=" + strconv.FormatBool(p.ConvertWebp)}
	case CrawlFetchThumbnails:
		start := maxInt(1, p.ThumbnailStartID)
		end := maxInt(start, p.ThumbnailEndID)
		return []string{
			"crawler", "fetch-thumbnails",
			"--start-id", strconv.Itoa(start),
			"--end-id", strconv.Itoa(end),
			"--convert-webp=" + strconv.FormatBool(p.ConvertWebp),
		}
	}

	startPage := maxInt(1, p.StartPage)
	pages := maxInt(0, p.Pages)
	pageDelay := maxInt(0, p.PageDelaySeconds)
	loopDelay := maxInt(0, p.LoopDelaySeconds)
	loop := p.Loop
	if p.Mode == CrawlMonitor {
		// Monitor always crawls the newest pages in a loop; the user still
		// controls the per-page and per-round delays.
		startPage = 1
		pages = maxInt(1, p.MonitorPages)
		loop = true
	}

	args := []string{
		"crawler",
		"--start-page", strconv.Itoa(startPage),
		"--pages", strconv.Itoa(pages),
		"--page-delay", strconv.Itoa(pageDelay),
	}
	if loop {
		args = append(args, "--loop", "--loop-delay", strconv.Itoa(loopDelay))
	}
	args = append(args,
		"--post-batch-size", strconv.Itoa(clampInt(p.PostBatchSize, 1, 200)),
		"--comment-limit", strconv.Itoa(clampInt(p.CommentLimit, 1, 200)),
	)
	// Only the crawl subcommands (sequential/monitor) reach this point.
	if p.FetchImages {
		args = append(args, "--fetch-images")
	}
	if p.SaveRawJSON {
		args = append(args, "--save-raw-json")
	}
	return append(args, "--convert-webp="+strconv.FormatBool(p.ConvertWebp))
}

// jobAlive reports whether the job's process is still running. The process
// must still be a crawler so a recycled PID is not mistaken for the job.
func jobAlive(pid int) bool {
	if pid <= 0 {
		return false
	}
	data, err := os.ReadFile(filepath.Join("/proc", strconv.Itoa(pid), "cmdline"))
	if err != nil {
		return false
	}
	return strings.Contains(strings.ReplaceAll(string(data), "\x00", " "), "crawler")
}

// jobProgressLine extracts the last crawler progress line from the job log.
func jobProgressLine(job CrawlerJob) string {
	path, err := jobLogPath(job)
	if err != nil {
		return ""
	}
	tail, err := readFileTail(path, 8192)
	if err != nil {
		return ""
	}
	last := ""
	for _, line := range strings.Split(tail, "\n") {
		if strings.Contains(line, "[Crawler]") {
			last = strings.TrimSpace(line)
		}
	}
	return last
}

func readFileTail(path string, maxBytes int64) (string, error) {
	file, err := os.Open(path)
	if err != nil {
		return "", err
	}
	defer file.Close()

	info, err := file.Stat()
	if err != nil {
		return "", err
	}
	offset := int64(0)
	if info.Size() > maxBytes {
		offset = info.Size() - maxBytes
	}
	if _, err := file.Seek(offset, io.SeekStart); err != nil {
		return "", err
	}
	data, err := io.ReadAll(file)
	if err != nil {
		return "", err
	}
	return string(data), nil
}

// jobLauncherFunc starts a detached crawler process and returns its PID.
type jobLauncherFunc func(job CrawlerJob) (int, error)

// launchJobProcess is swappable so tests do not spawn real processes.
var launchJobProcess jobLauncherFunc = defaultLaunchProcess

// defaultLaunchProcess starts the job with nohup-like semantics: a new session
// (Setsid) so the TUI's exit or terminal close cannot take it down, output
// redirected into the job's own log file.
func defaultLaunchProcess(job CrawlerJob) (int, error) {
	exe, err := os.Executable()
	if err != nil {
		return 0, err
	}
	cwd, err := os.Getwd()
	if err != nil {
		return 0, err
	}
	logPath, err := jobLogPath(job)
	if err != nil {
		return 0, err
	}
	if err := os.MkdirAll(filepath.Dir(logPath), 0755); err != nil {
		return 0, err
	}
	logFile, err := os.OpenFile(logPath, os.O_CREATE|os.O_WRONLY|os.O_APPEND, 0644)
	if err != nil {
		return 0, err
	}
	defer logFile.Close()

	cmd := exec.Command(exe, jobArgs(job)...)
	cmd.Dir = cwd
	cmd.Env = append(os.Environ(), "TREEHOLE_CRAWLER_LOG="+logPath)
	cmd.Stdout = logFile
	cmd.Stderr = logFile
	cmd.SysProcAttr = &syscall.SysProcAttr{Setsid: true}
	if err := cmd.Start(); err != nil {
		return 0, err
	}
	// Reap the process when it ends; this does not tie its lifetime to the TUI.
	go func() { _ = cmd.Wait() }()
	return cmd.Process.Pid, nil
}

func stopCrawlerJob(job CrawlerJob) error {
	if !jobAlive(job.PID) {
		return fmt.Errorf("任务未在运行")
	}
	return syscall.Kill(job.PID, syscall.SIGTERM)
}

// goRunTempBinary reports whether the running executable is a `go run` build
// under the module cache (starting jobs from it works, but a built binary is
// the intended runtime).
func goRunTempBinary() bool {
	exe, err := os.Executable()
	if err != nil {
		return false
	}
	return strings.Contains(exe, string(filepath.Separator)+"go-build")
}

func crawlModeShort(mode CrawlMode) string {
	switch mode {
	case CrawlMonitor:
		return "监控"
	case CrawlFetchImages:
		return "补图"
	case CrawlFetchThumbnails:
		return "缩略图"
	default:
		return "顺序"
	}
}

// jobSummary renders the one-line parameter summary shown next to a job.
func jobSummary(job CrawlerJob) string {
	p := job.Params
	switch p.Mode {
	case CrawlFetchImages:
		return fmt.Sprintf("补图 · WebP %s", onOff(p.ConvertWebp))
	case CrawlFetchThumbnails:
		return fmt.Sprintf("缩略图 %d-%d · WebP %s", p.ThumbnailStartID, p.ThumbnailEndID, onOff(p.ConvertWebp))
	case CrawlMonitor:
		return fmt.Sprintf("监控前 %d 页 · 间隔 %ds · posts %d", p.MonitorPages, p.LoopDelaySeconds, p.PostBatchSize)
	default:
		loop := "单轮"
		if p.Loop {
			loop = fmt.Sprintf("循环 %ds", p.LoopDelaySeconds)
		}
		return fmt.Sprintf("起始 %d 页 · %s · posts %d", p.StartPage, loop, p.PostBatchSize)
	}
}
